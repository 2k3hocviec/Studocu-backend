async function seedSubscriptionsAndPayments(
  users: Awaited<ReturnType<typeof seedUsers>>,
  plans: Awaited<ReturnType<typeof seedPlans>>,
) {
  const premiumUser = users["premium@hoclieu.local"];
  const plan = plans["Sinh vien"];
  const startDate = new Date("2026-06-01T00:00:00.000Z");
  const endDate = new Date("2026-08-30T00:00:00.000Z");

  const existingSubscription = await prisma.subscription.findFirst({
    where: { userId: premiumUser.id, planId: plan.id, status: SubscriptionStatus.ACTIVE },
  });
  if (existingSubscription) {
    await prisma.subscription.update({
      where: { id: existingSubscription.id },
      data: { startDate, endDate, status: SubscriptionStatus.ACTIVE },
    });
  } else {
    await prisma.subscription.create({
      data: { userId: premiumUser.id, planId: plan.id, startDate, endDate, status: SubscriptionStatus.ACTIVE },
    });
  }

  const existingPayment = await prisma.payment.findFirst({
    where: { userId: premiumUser.id, planId: plan.id, method: PaymentMethod.MOCK, status: PaymentStatus.PAID },
  });
  if (existingPayment) {
    await prisma.payment.update({
      where: { id: existingPayment.id },
      data: { amount: plan.price, paidAt: startDate },
    });
  } else {
    await prisma.payment.create({
      data: {
        userId: premiumUser.id,
        planId: plan.id,
        amount: plan.price,
        method: PaymentMethod.MOCK,
        status: PaymentStatus.PAID,
        paidAt: startDate,
      },
    });
  }
}

