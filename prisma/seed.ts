type DocumentSeed = {
  title: string;
  description: string;
  uploaderId: number;
  schoolId?: number | null;
  subjectId?: number | null;
  requestedSchoolName?: string | null;
  requestedSubjectName?: string | null;
  documentType: DocumentType;
  status: DocumentStatus;
  pages: number;
  downloads: number;
  fileType?: FileType;
  storageProvider?: StorageProvider;
  approvedBy?: number | null;
  rejectReason?: string | null;
  previewCount?: number;
};

async function upsertDocument(document: DocumentSeed) {
  const existing = await prisma.document.findFirst({
    where: { title: document.title },
    orderBy: { id: "asc" },
  });

  const isApproved = document.status === DocumentStatus.APPROVED;
  const data = {
    schoolId: document.schoolId ?? null,
    subjectId: document.subjectId ?? null,
    requestedSchoolName: document.requestedSchoolName ?? null,
    requestedSubjectName: document.requestedSubjectName ?? null,
    title: document.title,
    description: document.description,
    documentType: document.documentType,
    status: document.status,
    downloadCount: document.downloads,
    viewCount: document.downloads * 3,
    approvedBy: isApproved ? document.approvedBy ?? null : null,
    approvedAt: isApproved ? new Date("2026-06-01T08:00:00.000Z") : null,
    rejectReason: document.rejectReason ?? null,
  };
  const fileType = document.fileType ?? FileType.PDF;
  const localFile = await writeSeedDocumentFile(document.title, document.pages);
  const file = {
    fileUrl: localFile.fileUrl,
    originalFilename: localFile.filename,
    fileType,
    fileSize: localFile.fileSize,
    totalPages: document.pages,
    storageProvider: StorageProvider.LOCAL,
  };

  const saved = existing
    ? await prisma.document.update({
        where: { id: existing.id },
        data: {
          ...data,
          documentFile: {
            upsert: {
              update: file,
              create: file,
            },
          },
        },
      })
    : await prisma.document.create({
        data: {
          uploaderId: document.uploaderId,
          ...data,
          documentFile: { create: file },
        },
      });

  await prisma.documentPreview.deleteMany({ where: { documentId: saved.id } });
  const previewCount = Math.min(document.previewCount ?? 3, document.pages);
  if (previewCount > 0) {
    await prisma.documentPreview.createMany({
      data: Array.from({ length: previewCount }, (_, index) => ({
        documentId: saved.id,
        pageNumber: index + 1,
        imageUrl: previewImage(document.title, index + 1),
        isBlurred: false,
      })),
    });
  }

  return saved;
}

