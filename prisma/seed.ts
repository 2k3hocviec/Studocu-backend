async function repairMissingDocumentFiles() {
  const files = await prisma.documentFile.findMany({
    include: { document: { select: { title: true } } },
  });

  for (const file of files) {
    if (await localDocumentExists(file.fileUrl)) continue;

    const localFile = await writeSeedDocumentFile(file.document.title, file.totalPages ?? 3);
    await prisma.documentFile.update({
      where: { id: file.id },
      data: {
        fileUrl: localFile.fileUrl,
        originalFilename: localFile.filename,
        fileType: FileType.PDF,
        fileSize: localFile.fileSize,
        storageProvider: StorageProvider.LOCAL,
      },
    });
  }
}

