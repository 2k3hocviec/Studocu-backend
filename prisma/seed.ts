function previewImage(title: string, pageNumber: number) {
  return `https://placehold.co/820x1160/png?text=${encodeURIComponent(`${title} - Trang ${pageNumber}`)}`;
}

function slugify(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90) || "document";
}

function pdfText(value: string) {
  return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function buildSeedPdf(title: string, pageCount: number) {
  const pages = Math.max(1, pageCount);
  const fontObjectId = pages * 2 + 3;
  const objects: string[] = [];
  const pageObjectIds: number[] = [];

  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";

  for (let index = 0; index < pages; index += 1) {
    const pageObjectId = index * 2 + 3;
    const contentObjectId = index * 2 + 4;
    pageObjectIds.push(pageObjectId);

    const stream = [
      "BT",
      "/F1 18 Tf",
      "72 740 Td",
      `(${pdfText(title)}) Tj`,
      "0 -32 Td",
      "/F1 12 Tf",
      `(Seed document page ${index + 1} of ${pages}) Tj`,
      "0 -24 Td",
      "(This file is generated by prisma/seed.ts so /documents/:id/file can stream a real PDF.) Tj",
      "ET",
    ].join("\n");

    objects[pageObjectId] = [
      "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792]",
      `/Resources << /Font << /F1 ${fontObjectId} 0 R >> >>`,
      `/Contents ${contentObjectId} 0 R >>`,
    ].join(" ");
    objects[contentObjectId] = `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`;
  }

  objects[2] = `<< /Type /Pages /Kids [${pageObjectIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pages} >>`;
  objects[fontObjectId] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";

  let body = "%PDF-1.4\n";
  const offsets = [0];
  for (let id = 1; id < objects.length; id += 1) {
    if (!objects[id]) continue;
    offsets[id] = Buffer.byteLength(body);
    body += `${id} 0 obj\n${objects[id]}\nendobj\n`;
  }

  const xrefOffset = Buffer.byteLength(body);
  body += `xref\n0 ${objects.length}\n`;
  body += "0000000000 65535 f \n";
  for (let id = 1; id < objects.length; id += 1) {
    body += `${String(offsets[id] ?? 0).padStart(10, "0")} 00000 n \n`;
  }
  body += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(body, "utf8");
}

async function writeSeedDocumentFile(title: string, pageCount: number) {
  await mkdir(localDocumentDir, { recursive: true });
  const filename = `seed-${slugify(title)}.pdf`;
  const buffer = buildSeedPdf(title, pageCount);
  await writeFile(path.join(localDocumentDir, filename), buffer);
  return {
    filename,
    fileUrl: `${localDocumentPrefix}${encodeURIComponent(filename)}`,
    fileSize: buffer.length,
  };
}

async function localDocumentExists(fileUrl: string) {
  if (!fileUrl.startsWith(localDocumentPrefix)) return false;
  const filename = decodeURIComponent(fileUrl.slice(localDocumentPrefix.length));
  try {
    await access(path.join(localDocumentDir, filename));
    return true;
  } catch {
    return false;
  }
}

